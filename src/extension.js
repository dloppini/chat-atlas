  // Registers through each agent's own CLI, so their config files are never edited directly.
  async function registerMcp() {
    if (vscode.env.remoteName) throw new Error('The MCP server is available in local VS Code windows.');
    await launcherReady;
    await fs.access(mcpLauncher).catch(() => { throw new Error('The MCP launcher could not be written to VS Code storage.'); });
    await runAgent('node', ['--version']).catch(() => { throw new Error('Install Node.js and add it to PATH. Agents start the Chat Atlas MCP server with node.'); });
    const c = vscode.workspace.getConfiguration('chatAtlas');
    const claude = vscode.extensions?.getExtension('anthropic.claude-code'), codex = vscode.extensions?.getExtension('openai.chatgpt');
    const agents = [
      { name: 'Claude Code', fallback: 'claude', env: c.get('claudeHome') ? { CLAUDE_CONFIG_DIR: c.get('claudeHome') } : {},
        bundled: claude && path.join(claude.extensionPath, 'resources', 'native-binary', process.platform === 'win32' ? 'claude.exe' : 'claude'),
        remove: ['mcp', 'remove', '--scope', 'user', 'chat-atlas'], add: ['mcp', 'add', '--scope', 'user', 'chat-atlas', '--', 'node', mcpLauncher] },
      { name: 'Codex', fallback: 'codex', env: c.get('codexHome') ? { CODEX_HOME: c.get('codexHome') } : {},
        bundled: codex && await codexBinary(codex.extensionPath).catch(() => undefined),
        remove: ['mcp', 'remove', 'chat-atlas'], add: ['mcp', 'add', 'chat-atlas', '--', 'node', mcpLauncher] }
    ];
    const registered = [], failed = [];
    for (const agent of agents) {
      const binary = agent.bundled && await fs.stat(agent.bundled).then(stat => stat.isFile() && agent.bundled, () => false) || agent.fallback;
      try {
        await runAgent(binary, agent.remove, agent.env).catch(() => { /* Nothing registered yet. */ });
        await runAgent(binary, agent.add, agent.env);
        registered.push(agent.name);
      } catch (error) {
        if (error.code !== 'ENOENT') failed.push(`${agent.name}: ${error.detail || error.message}`);
      }
    }
    if (!registered.length && !failed.length) throw new Error('Install Claude Code or Codex to connect an agent.');
    return [registered.length && `Chat Atlas MCP server registered with ${registered.join(' and ')}. Start a new agent session to use it.`, ...failed].filter(Boolean).join(' ');
  }
