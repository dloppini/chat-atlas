    await vscode.env.clipboard.writeText(choice.value);
    vscode.window.showInformationMessage(choice.label === 'Codex' ? 'Copied. Add it to ~/.codex/config.toml.' : choice.label === 'Claude Code' ? 'Copied. Run it in a terminal; Node must be on PATH.' : 'Launcher path copied.');
